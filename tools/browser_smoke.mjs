/** Optional browser verification; install playwright separately and use existing Chrome. */
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.CODELENS_PLAYWRIGHT_MODULE || 'playwright');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const url = process.env.CODELENS_TEST_URL || 'http://127.0.0.1:8765';
const browser = await chromium.launch({channel:'chrome', headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1060},acceptDownloads:true});
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const account = `browser_${Date.now()}`;
try {
  await page.goto(url);
  await page.getByRole('heading', {name:'欢迎回来'}).waitFor();
  await page.screenshot({path:resolve(tmpdir(),'codelens-login.png')});
  await page.getByRole('button', {name:'创建账号', exact:true}).click();
  await page.getByLabel('用户名', {exact:true}).fill(account);
  await page.getByLabel('密码', {exact:true}).fill('browser-verification-password');
  await page.getByRole('button', {name:'创建账号并进入'}).click();
  await page.getByRole('heading', {name:'全班作品，一次复核。'}).waitFor();
  await page.screenshot({path:resolve(tmpdir(),'codelens-workspace.png'),fullPage:true});
  const overflowDesktop = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflowDesktop,false);
  await page.getByRole('button', {name:'双版本示例',exact:true}).click();
  await page.locator('#result-content .status.completed').waitFor({timeout:12000});
  assert.equal(await page.locator('#pair-table tbody tr').count(),7);
  await page.getByLabel('筛选语言').selectOption('JavaScript');
  assert.equal(await page.locator('#pair-table tbody tr').count(),1);
  await page.getByRole('button', {name:'查看证据'}).click();
  await page.getByRole('heading', {name:'原始代码证据'}).waitFor();
  assert.equal(await page.locator('#evidence-container .fragment').count(),2);
  assert.ok((await page.locator('#pair-table').textContent()).includes('片段整体换序'));
  await page.locator('#evidence-container .fragment').nth(1).locator('summary').click();
  assert.equal(await page.locator('#evidence-container .fragment[open]').count(),2);
  await page.locator('#evidence-container [data-expand-code]').first().click();
  assert.equal(await page.locator('#evidence-container .code-box.expanded').count(),1);
  await page.screenshot({path:resolve(tmpdir(),'codelens-result.png'),fullPage:true});
  await page.getByLabel('搜索文件路径').fill('this-file-does-not-exist');
  await page.getByRole('heading', {name:'没有符合筛选条件的文件对'}).waitFor();
  assert.equal(await page.locator('#evidence-container .fragment').count(),0);
  await page.getByRole('button', {name:'重置',exact:true}).click();
  assert.equal(await page.locator('#pair-table tbody tr').count(),7);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', {name:'导出 HTML'}).click();
  const download = await downloadEvent;
  await mkdir(resolve(root,'reports'), {recursive:true});
  await download.saveAs(resolve(root,'reports/sample-report.html'));
  const reportPath = resolve(root,'reports/sample-report.html');
  const reportPage = await context.newPage();
  await reportPage.goto('file://' + reportPath);
  assert.equal(await reportPage.locator('.pair').count(),7);
  assert.equal(await reportPage.locator('.fragment').count(),8);
  assert.equal(await reportPage.locator('script[data-codelens-controls]').count(),1);
  await reportPage.close();
  const firstReportHref = await page.getByRole('link', {name:'导出 HTML'}).getAttribute('href');
  await page.getByRole('button', {name:'重新分析',exact:true}).click();
  await page.waitForFunction(previous => {
    const link = document.querySelector('#result-content a[download]');
    return link && link.getAttribute('href') !== previous;
  }, firstReportHref, {timeout:12000});
  await page.locator('#result-content .status.completed').waitFor({timeout:12000});
  await page.getByRole('button', {name:'返回分析记录'}).click();
  assert.equal(await page.locator('#history-content tbody tr').count(),2);
  await page.getByRole('button', {name:'新建分析',exact:true}).click();
  await page.getByRole('button', {name:'双版本分析',exact:true}).click();
  await page.locator('#a-url').fill('https://github.com/githubtraining/hellogitworld.git');
  await page.locator('#b-url').fill('https://github.com/githubtraining/hellogitworld.git');
  await page.locator('#a-branch').fill('master');
  // B omitted: verifies remote default branch discovery in the complete browser flow.
  await page.getByRole('button', {name:'开始双版本分析'}).click();
  await page.locator('#result-content .status.completed').waitFor({timeout:20000});
  assert.equal(await page.locator('.metric-card.highlight .metric-value strong').textContent(),'100.0');
  assert.ok((await page.locator('#result-content').textContent()).includes('相同提交'));
  assert.equal(await page.locator('#pair-table tbody tr').count(),2);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
  await page.screenshot({path:resolve(tmpdir(),'codelens-mobile.png'),fullPage:true});
  await page.getByRole('button', {name:'退出登录'}).click();
  await page.getByRole('heading', {name:'创建你的工作空间'}).waitFor();
  assert.equal(await page.locator('#result-content').textContent(),'');
  await page.getByRole('button', {name:'直接登录',exact:true}).click();
  await page.getByLabel('用户名',{exact:true}).fill(account);
  await page.getByLabel('密码',{exact:true}).fill('browser-verification-password');
  await page.getByRole('button',{name:'登录工作台'}).click();
  await page.getByRole('heading', {name:'全班作品，一次复核。'}).waitFor();
  await page.getByRole('button', {name:/分析记录/}).first().click();
  assert.equal(await page.locator('#history-content tbody tr').count(),3);
  await page.getByRole('button', {name:'退出登录'}).click();
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,account,desktopOverflow:overflowDesktop,mobileOverflow:false,report:reportPath,consoleErrors:errors,
    checks:['registration','login','demo','7 languages','function reorder','evidence expansion','filters','offline HTML','history persistence','real Git/default branch','mobile layout','logout']},null,2));
} finally {
  await browser.close();
}
