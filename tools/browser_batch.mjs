/** Batch UI verification; Playwright is installed outside the project. */
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.CODELENS_PLAYWRIGHT_MODULE || 'playwright');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const url = process.env.CODELENS_TEST_URL || 'http://127.0.0.1:8765';
const browser = await chromium.launch({channel:'chrome',headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1040},acceptDownloads:true});
const page = await context.newPage();
const errors = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
const account = `batch_browser_${Date.now()}`;
try {
  await page.goto(url);
  await page.getByRole('button',{name:'创建账号',exact:true}).click();
  await page.getByLabel('用户名',{exact:true}).fill(account);
  await page.getByLabel('密码',{exact:true}).fill('batch-browser-verification');
  await page.getByRole('button',{name:'创建账号并进入'}).click();
  await page.getByRole('heading',{name:'全班作品，一次复核。'}).waitFor();
  assert.equal(await page.locator('#pair-sources').isVisible(),false);
  await page.route('**/api/branches', route => route.fulfill({json:{branches:Array.from({length:55},(_,i)=>({branch:`student-${String(i+1).padStart(3,'0')}`,commit:'fixture-only'}))}}));
  await page.locator('#batch-url').fill('https://github.com/example/graduation.git');
  await page.getByRole('button',{name:'加载远端分支'}).click();
  await page.getByText('已读取 55 个分支；请勾选学生作品。').waitFor();
  await page.locator('#branch-search').fill('student-00');
  await page.getByRole('button',{name:'选择搜索结果'}).click();
  assert.equal((await page.locator('#manual-branches').inputValue()).split('\n').length,9);
  await page.locator('#branch-search').fill('student-050');
  await page.getByRole('button',{name:'选择搜索结果'}).click();
  assert.equal((await page.locator('#manual-branches').inputValue()).split('\n').length,10);
  await page.getByRole('button',{name:'清空搜索结果'}).click();
  assert.equal((await page.locator('#manual-branches').inputValue()).split('\n').length,9);
  await page.unroute('**/api/branches');
  checks.push('branch picker search / selection retention (mocked branch response)');
  await page.locator('#manual-branches').fill('one\t作品一\ntwo\t作品二\nthree\t作品三');
  assert.ok((await page.locator('#batch-count').textContent()).includes('3 个待比较作品对'));
  await page.locator('#batch-url').fill('https://github.com/example/graduation.git');
  await page.locator('#batch-baseline').fill('one');
  await page.getByRole('button',{name:'开始批量查重'}).click();
  await page.getByText('教师模板不能同时作为学生作品。',{exact:true}).waitFor();
  checks.push('batch form/count/template validation');
  await page.getByRole('button',{name:'体验 50 分支示例'}).click();
  await page.locator('#result-content .status.completed').waitFor({timeout:15000});
  assert.equal(await page.locator('.batch-matrix tbody tr').count(),50);
  assert.equal(await page.locator('.batch-matrix tbody td').count(),2500);
  assert.equal(await page.locator('.batch-matrix .unavailable').count(),98);
  assert.equal(await page.locator('#batch-pair-list tbody tr').count(),30);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
  const matrixScroll = await page.locator('.batch-matrix').evaluate(el => ({horizontal:el.scrollWidth > el.clientWidth,vertical:el.scrollHeight > el.clientHeight}));
  assert.ok(matrixScroll.horizontal && matrixScroll.vertical);
  await page.locator('.batch-matrix').evaluate(el => {el.scrollLeft = 700; el.scrollTop = 500;});
  await page.screenshot({path:resolve(tmpdir(),'codelens-batch-50.png'),fullPage:true});
  checks.push('50x50 matrix / 1225 pairs / N/A / independent scroll');
  await page.locator('[data-batch-scope="raw"]').click();
  await page.locator('#batch-only-review').uncheck();
  assert.ok((await page.locator('.batch-pagination').textContent()).includes('1225 个作品对'));
  await page.locator('[data-batch-page="1"]').click();
  assert.ok((await page.locator('.batch-pagination').textContent()).includes('第 2/'));
  await page.locator('#batch-pair-search').fill('示例作品 001');
  assert.ok((await page.locator('.batch-pagination').textContent()).includes('49 个作品对'));
  await page.locator('[data-batch-scope="adjusted"]').click();
  checks.push('scope toggle / pagination / student search');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link',{name:'导出批次 HTML'}).click();
  await mkdir(resolve(root,'reports'),{recursive:true});
  await (await downloadEvent).saveAs(resolve(root,'reports/batch-50-report.html'));
  const overview = await context.newPage();
  await overview.goto('file://' + resolve(root,'reports/batch-50-report.html'));
  assert.equal(await overview.locator('.matrix').count(),2);
  assert.equal(await overview.locator('script').count(),0);
  assert.ok((await overview.locator('body').textContent()).includes('不含全部代码证据'));
  await overview.close();
  checks.push('downloaded offline overview');
  await page.locator('#batch-pair-list [data-batch-pair]').first().click();
  await page.getByRole('button',{name:'返回批次矩阵'}).waitFor();
  await page.locator('#pair-table [data-pair]').first().click();
  await page.getByRole('heading',{name:'原始代码证据'}).waitFor();
  assert.ok(await page.locator('.fragment').count() > 0);
  const adjustedTokens = await page.locator('.metric-card').nth(1).textContent();
  await page.getByRole('button',{name:'原始证据',exact:true}).click();
  await page.getByText('当前：原始口径',{exact:false}).waitFor();
  assert.notEqual(await page.locator('.metric-card').nth(1).textContent(),adjustedTokens);
  const pairDownload = page.waitForEvent('download');
  await page.getByRole('link',{name:'导出 HTML'}).click();
  await (await pairDownload).saveAs(resolve(root,'reports/batch-pair-report.html'));
  const pair = await context.newPage();
  await pair.goto('file://'+resolve(root,'reports/batch-pair-report.html'));
  assert.ok(await pair.locator('.fragment').count() > 0);
  assert.equal(await pair.locator('script[data-codelens-controls]').count(),1);
  await pair.close();
  checks.push('lazy evidence / raw and adjusted / offline pair report');
  await page.getByRole('button',{name:'返回批次矩阵'}).click();
  await page.locator('.batch-matrix').waitFor();
  await page.reload();
  await page.getByRole('button',{name:/分析记录/}).first().click();
  await page.locator('#history-content [data-job]').first().click();
  await page.locator('.batch-matrix').waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
  await page.screenshot({path:resolve(tmpdir(),'codelens-batch-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'退出登录'}).click();
  await page.locator('#auth-screen').waitFor({state:'visible'});
  assert.equal(await page.locator('#result-content').textContent(),'');
  assert.equal(await page.locator('#manual-branches').inputValue(),'');
  assert.equal(await page.locator('#batch-token').inputValue(),'');
  await page.goto(url+'/prd/prd.html');
  assert.ok((await page.locator('h1').textContent()).includes('全班作品'));
  await page.locator('#demo-count').fill('60');
  assert.ok((await page.locator('#count-feedback').textContent()).includes('1,770'));
  assert.deepEqual(errors,[]);
  checks.push('history refresh / mobile / logout clear / PRD v2 interaction');
  console.log(JSON.stringify({passed:true,checks,consoleErrors:errors,report:resolve(root,'reports/batch-50-report.html')},null,2));
} finally {
  await browser.close();
}
